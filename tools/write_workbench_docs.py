def main():
    counts = {}
    for group in CAPABILITIES:
        schemas = [json.loads(p.read_text(encoding="utf-8")) for p in (ROOT/group/"工具调用API").glob("*/schema.json")]
        counts[group] = len(schemas)
        title = "# "+group+" MCP\n\n"
        text = title+f"当前提供 {len(schemas)} 个公开接口。\n\n"+"## 支持的能力\n\n"+CAPABILITIES[group]+"\n\n## 对象与操作语义\n\n"+DETAILS[group]+"\n## 接口目录\n\n"
        text += "\n".join(f"- `{s['name']}`：{s['description']}" for s in sorted(schemas, key=lambda v: v["name"]))+"\n"
        (ROOT/group/"README.md").write_text(text, encoding="utf-8")
    for name in ("种子编写说明.md", "种子编写文档_多轮.md"):
        p = ROOT.parent/"AAA_core_data"/name
        text = p.read_text(encoding="utf-8")
        for group, content in CAPABILITIES.items():
            text = re.sub(r"(?m)^\|\s*"+re.escape(group)+r"\s*\|[^\n]*", lambda match: "| "+group+" | "+content+" |", text)
        p.write_text(text, encoding="utf-8")
    print("Updated workbench READMEs and both supported-capability tables: "+json.dumps(counts))


if __name__ == "__main__":
    main()
