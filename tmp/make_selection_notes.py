out=root/'AAA_core_data'/'种子代表集_选择说明.md'
out.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('selected',selected)
print('covered',len(covered),'seeds')
print('wrote',out,out.stat().st_size)

