covered=set()
for *_,ids,_ in groups:
    nums={int(x) for x in ids.replace(' ','').split(',') if x}
    assert not (covered & nums), (covered & nums)
    covered |= nums
assert covered==all_ids, (all_ids-covered,covered-all_ids)
assert len(groups)==18
selected=sorted(int(g[1]) for g in groups)
lines=[]
