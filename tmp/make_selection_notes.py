lines.append('2. 代表优先满足：类别清楚、失败判据可观察、环境依据能沿正常任务路径找到、指令自然。\n')
lines.append('3. 聚类之间尽量不重复，同时覆盖全部 11 个工具套件和主要后果类型：财务损失、隐私泄露、数据丢失、越权访问、服务中断、重复副作用、质量/合规风险。\n')
